_recent = []


def pick(kind: str, **fmt) -> str:
    pool = POOLS.get(kind, POOLS["playful"])
    candidates = [m for m in pool if m not in _recent[-10:]] or pool
    msg = random.choice(candidates)
    _recent.append(msg)
    if len(_recent) > 40:
        del _recent[:-25]
    try:
        return msg.format(**fmt)
    except Exception:
        return msg
